def git(dest, *args, env=None):
    subprocess.run(["git", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", *args],
                   cwd=dest, env=env, check=True, capture_output=True)


def build(dest):
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    git(dest, "init", "-q", "-b", "main")
    for index, (message, files) in enumerate(COMMITS):
        for path, content in files.items():
            target = dest / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        date = (FIRST_COMMIT + index * COMMIT_SPACING).isoformat()
        env = {**os.environ, "GIT_AUTHOR_NAME": "Fixture", "GIT_AUTHOR_EMAIL": "fixture@example.com",
               "GIT_COMMITTER_NAME": "Fixture", "GIT_COMMITTER_EMAIL": "fixture@example.com",
               "GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date}
        git(dest, "add", "-A")
        git(dest, "commit", "-q", "-m", message, env=env)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: build.py DEST")
    build(sys.argv[1])
